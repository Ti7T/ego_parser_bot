def get_language(user_id: int) -> str:
    language = get_user_language(user_id)
    return language if language in LANGUAGES else "ru"

def set_language(user_id: int, language: str) -> None:
    if language not in LANGUAGES:
        raise ValueError(f"Unsupported language: {language}")
    from database.languages import set_user_language
    set_user_language(user_id, language)

def t(user_id: int, key: str, **kwargs) -> str:
    language = get_language(user_id)
    template = TEXTS.get(language, TEXTS["ru"]).get(key, TEXTS["ru"].get(key, key))
    return template.format(**kwargs) if kwargs else template
